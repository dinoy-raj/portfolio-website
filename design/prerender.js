// Pre-renders every page of the site to static HTML, so each one paints before any script loads and crawlers that
// don't run JavaScript still see the right page:
//   index.html                              the home page, rendered into #root in place
//   <slug>/index.html                       each app page (served at /<slug>)
//   <slug>/privacypolicy/index.html, ...    its legal pages (served at /<slug>/privacypolicy and /<slug>/termsofservice)
// The route pages are copies of index.html with their own <title>, description, canonical URL, Open Graph and Twitter tags,
// JSON-LD and pre-rendered body. React hydrates that markup in place instead of redrawing it.
// Re-run after changing anything in index.html (content, styles or script), or the route pages fall behind:
//   node design/prerender.js
// Needs Playwright (pre-installed in Claude Code cloud sessions; elsewhere: npm i -g playwright) and network access to cdnjs.
const { chromium } = require('playwright');
const fs = require('fs'), path = require('path'), http = require('http');

const ROOT = path.join(__dirname, '..');
const SITE = 'https://dinoyraj.com';
const START = '<!-- prerender:start -->', END = '<!-- prerender:end -->';
const SERVER = 'https://cdnjs.cloudflare.com/ajax/libs/react-dom/18.3.1/umd/react-dom-server-legacy.browser.production.min.js';
const LEGAL = ['privacypolicy', 'termsofservice'];
const GENERATED = '<!-- Generated by design/prerender.js from index.html. Edit index.html and re-run it instead of editing this file. -->';
const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.svg': 'image/svg+xml',
  '.png': 'image/png', '.jpg': 'image/jpeg', '.webp': 'image/webp', '.ico': 'image/x-icon', '.woff2': 'font/woff2', '.xml': 'application/xml', '.txt': 'text/plain' };

const read = f => fs.readFileSync(path.join(ROOT, f), 'utf8');
const esc = s => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// Every app route comes from the slugs in APPS, so a new app gets its pages without touching this script.
function routes(src) {
  const slugs = [...new Set([...src.matchAll(/\bslug: '([a-z0-9-]+)'/g)].map(m => m[1]))];
  if (!slugs.length) throw new Error('no app slugs found in index.html');
  return slugs.flatMap(s => ['/' + s, ...LEGAL.map(l => '/' + s + '/' + l)]);
}

// Serves the working tree, with index.html at "/" and every app route, as Vercel did before the route pages existed.
function serve(routeSet) {
  const server = http.createServer((req, res) => {
    const p = decodeURIComponent(new URL(req.url, 'http://x').pathname);
    const file = p === '/' || routeSet.has(p) ? path.join(ROOT, 'index.html') : path.join(ROOT, p);
    if (!file.startsWith(ROOT) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) { res.writeHead(404); return res.end(); }
    res.writeHead(200, { 'Content-Type': TYPES[path.extname(file)] || 'application/octet-stream' });
    fs.createReadStream(file).pipe(res);
  });
  return new Promise(ok => server.listen(0, '127.0.0.1', () => ok(server)));
}

// React's first render of the route, untouched by effects: the page hands its root element to this hook instead of mounting it.
async function markup(browser, url) {
  const p = await browser.newPage();
  await p.addInitScript(() => { window.__prerender = el => { window.__app = el; }; });
  await p.goto(url, { waitUntil: 'networkidle' });
  await p.waitForFunction(() => window.__app);
  await p.addScriptTag({ url: SERVER });
  const html = await p.evaluate(() => ReactDOMServer.renderToString(window.__app));
  await p.close();
  return html;
}

// The title, description, canonical URL and route key the running page sets for itself, so they're defined once, in index.html.
async function head(browser, url, want) {
  const p = await browser.newPage();
  await p.goto(url, { waitUntil: 'networkidle' });
  // The route's effect sets these once React has mounted; time out if it never points the canonical at this URL.
  await p.waitForFunction(w => (document.querySelector('link[rel=canonical]') || {}).href === w, want, { timeout: 15000 });
  const h = await p.evaluate(() => ({
    title: document.title,
    desc: document.querySelector('meta[name=description]').content,
    canonical: document.querySelector('link[rel=canonical]').href,
  }));
  await p.close();
  return h;
}

function replaceOnce(src, re, to, what) {
  const n = (src.match(new RegExp(re.source, 'g')) || []).length;
  if (n !== 1) throw new Error(`expected one ${what} in index.html, found ${n}`);
  return src.replace(re, to);
}

function withRoot(src, html, route) {
  const a = src.indexOf(START), z = src.indexOf(END);
  if (a < 0 || z < a) throw new Error('prerender markers not found in index.html');
  // No whitespace inside #root: hydration matches child nodes one for one.
  return src.slice(0, a + START.length) + '<div id="root"' + (route ? ` data-route="${route}"` : '') + '>' + html + '</div>' + src.slice(z);
}

function routePage(src, { title, desc, canonical }, html, route) {
  const t = esc(title), d = esc(desc), u = esc(canonical);
  let out = src;
  out = replaceOnce(out, /<title>[^<]*<\/title>/, `<title>${t}</title>`, '<title>');
  out = replaceOnce(out, /<meta name="description" content="[^"]*">/, `<meta name="description" content="${d}">`, 'meta description');
  out = replaceOnce(out, /<link rel="canonical" href="[^"]*">/, `<link rel="canonical" href="${u}">`, 'canonical');
  out = replaceOnce(out, /<meta property="og:type" content="[^"]*">/, '<meta property="og:type" content="website">', 'og:type');
  out = replaceOnce(out, /<meta property="og:title" content="[^"]*">/, `<meta property="og:title" content="${t}">`, 'og:title');
  out = replaceOnce(out, /<meta property="og:description" content="[^"]*">/, `<meta property="og:description" content="${d}">`, 'og:description');
  out = replaceOnce(out, /<meta property="og:url" content="[^"]*">/, `<meta property="og:url" content="${u}">`, 'og:url');
  out = replaceOnce(out, /<meta name="twitter:title" content="[^"]*">/, `<meta name="twitter:title" content="${t}">`, 'twitter:title');
  out = replaceOnce(out, /<meta name="twitter:description" content="[^"]*">/, `<meta name="twitter:description" content="${d}">`, 'twitter:description');
  // Profile tags describe the home page (og:type profile), and the hero portrait preload only helps the home page.
  out = out.replace(/<meta property="profile:[a-z_]+" content="[^"]*">\n/g, '');
  out = replaceOnce(out, /<link rel="preload" as="image" href="\/assets\/dinoy\.webp"[^>]*>\n/, '', 'hero preload');
  // JSON-LD: the Person and WebSite stay; the home page's ProfilePage becomes a WebPage for this URL.
  out = replaceOnce(out, /(<script type="application\/ld\+json">\n)([\s\S]*?)(\n<\/script>\n<!-- \/seo:jsonld -->)/, (m, a, json, z) => {
    const ld = JSON.parse(json);
    ld['@graph'] = ld['@graph'].map(n => n['@type'] !== 'ProfilePage' ? n : {
      '@type': 'WebPage', '@id': canonical + '#webpage', url: canonical, name: title, description: desc, inLanguage: 'en',
      isPartOf: { '@id': SITE + '/#website' }, author: { '@id': SITE + '/#person' },
    });
    return a + JSON.stringify(ld, null, 1).replace(/</g, '\\u003c') + z;
  }, 'JSON-LD block');
  out = replaceOnce(out, /^<!doctype html>\n/i, '<!doctype html>\n' + GENERATED + '\n', 'doctype');
  return withRoot(out, html, route);
}

(async () => {
  const src0 = read('index.html');
  const list = routes(src0);
  const server = await serve(new Set(list));
  const base = 'http://127.0.0.1:' + server.address().port;
  const browser = await chromium.launch();
  try {
    // Home first: it rewrites index.html, which every route page is then copied from.
    const home = await markup(browser, base + '/');
    const src = withRoot(src0, home);
    fs.writeFileSync(path.join(ROOT, 'index.html'), src);
    console.log('Pre-rendered ' + home.length + ' characters into index.html');

    const sitemap = read('sitemap.xml');
    for (const r of list) {
      const h = await head(browser, base + r, SITE + r);
      const [slug, legal] = r.slice(1).split('/');
      const key = (legal ? (legal === 'privacypolicy' ? 'privacy' : 'terms') : 'app') + ':' + slug;
      const html = await markup(browser, base + r);
      const file = path.join(ROOT, r.slice(1), 'index.html');
      fs.mkdirSync(path.dirname(file), { recursive: true });
      fs.writeFileSync(file, routePage(src, h, html, key));
      if (!sitemap.includes(`<loc>${SITE + r}</loc>`)) console.warn('  not in sitemap.xml: ' + r);
      console.log('Pre-rendered ' + r + ' -> ' + path.relative(ROOT, file));
    }
  } finally {
    await browser.close();
    server.close();
  }
})().catch(e => { console.error(e); process.exit(1); });
